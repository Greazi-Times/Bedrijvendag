function lookup(locale: Locale, key: string): string | undefined {
    let value: unknown = messages[locale];
    for (const part of key.split('.')) {
        if (!value || typeof value !== 'object' || !(part in value)) return undefined;
        value = (value as Record<string, unknown>)[part];
    }
    return typeof value === 'string' ? value : undefined;
}

export function useTranslations() {
    const page = usePage();
    const locale = computed<Locale>(() => (page.props.locale === 'en' ? 'en' : 'nl'));
    const dateLocale = computed(() => (locale.value === 'en' ? 'en-GB' : 'nl-NL'));

    const t = (key: string, replacements: Replacements = {}) => {
        let message = lookup(locale.value, key) ?? lookup('nl', key) ?? key;
        for (const [name, value] of Object.entries(replacements)) {
            message = message.replaceAll(`:${name}`, String(value));
        }
        return message;
    };

    return { locale, dateLocale, t };
}
