<?php

namespace App\Filament\Resources\Forms\Pages;

use App\Filament\Resources\Forms\FormResource;
use App\Filament\Resources\Forms\Schemas\FormBuilderSchema;
use App\Models\Event;
use App\Models\Form;
use App\Support\Forms\FormSchema;
use Filament\Actions\Action;
use Filament\Actions\DeleteAction;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Notifications\Notification;
use Filament\Resources\Pages\EditRecord;
use Illuminate\Validation\ValidationException;

class EditForm extends EditRecord
{
    protected static string $resource = FormResource::class;

    public function getSubheading(): ?string
    {
        $form = $this->getRecord();
        $version = $form->latestVersion?->version;
        $prefix = $form->isGlobal() ? 'Global default form. ' : '';

        return $prefix.($version ? "Published version {$version}. Saving only changes the draft." : 'Not published yet.');
    }

    protected function mutateFormDataBeforeSave(array $data): array
    {
        $data['draft_schema'] = FormBuilderSchema::normalize($data['draft_schema'] ?? []);

        return $data;
    }

    /** Show what was really saved, so keys generated on save are in the editor state and never regenerated by the next save. */
    protected function afterSave(): void
    {
        $this->form->fill([...$this->form->getRawState(), 'draft_schema' => $this->getRecord()->fresh()->draft_schema]);
    }

    protected function getHeaderActions(): array
    {
        return [
            Action::make('preview')
                ->label('Preview')
                ->icon('heroicon-o-eye')
                ->color('gray')
                ->modalSubmitAction(false)
                ->modalWidth('3xl')
                ->modalContent(fn (): \Illuminate\Contracts\View\View => view('filament.forms.preview', [
                    'schema' => FormBuilderSchema::normalize($this->form->getState()['draft_schema'] ?? []),
                    'problems' => FormSchema::problems(FormBuilderSchema::normalize($this->form->getState()['draft_schema'] ?? []), $this->getRecord()->kind),
                ])),
            Action::make('publish')
                ->label('Publish')
                ->icon('heroicon-o-rocket-launch')
                ->authorize('update')
                ->requiresConfirmation()
                ->modalDescription('Saves your changes and publishes them as a new version. Earlier submissions keep the version they were answered against.')
                ->action(function (): void {
                    $this->save(shouldRedirect: false);

                    try {
                        $version = $this->getRecord()->fresh()->publish(auth()->user());
                    } catch (ValidationException $e) {
                        Notification::make()->danger()->title('Cannot publish')->body(implode("\n", $e->errors()['draft_schema'] ?? []))->persistent()->send();

                        return;
                    }

                    Notification::make()->success()->title("Published version {$version->version}")->send();
                    $this->refreshFormData(['draft_schema']);
                }),
            Action::make('duplicate')
                ->label('Duplicate')
                ->icon('heroicon-o-document-duplicate')
                ->color('gray')
                ->authorize('create')
                ->form([
                    TextInput::make('name')->required()->default(fn (): string => $this->getRecord()->name.' (copy)'),
                    Select::make('event_id')->label('Edition')->placeholder('None (reusable template)')
                        ->options(fn (): array => Event::query()->orderByDesc('date')->pluck('name', 'id')->all()),
                ])
                ->action(function (array $data): void {
                    $copy = $this->getRecord()->duplicate(
                        filled($data['event_id'] ?? null) ? Event::findOrFail($data['event_id']) : null,
                        $data['name'],
                        asTemplate: blank($data['event_id'] ?? null),
                    );
                    $this->redirect(FormResource::getUrl('edit', ['record' => $copy]));
                }),
            Action::make('publishedVersion')
                ->label('Published version')
                ->icon('heroicon-o-document-check')
                ->color('gray')
                ->visible(fn (Form $record): bool => $record->latestVersion !== null)
                ->modalSubmitAction(false)
                ->modalWidth('3xl')
                ->modalHeading(fn (Form $record): string => 'Published version '.$record->latestVersion?->version)
                ->modalContent(fn (Form $record): \Illuminate\Contracts\View\View => view('filament.forms.preview', ['schema' => $record->latestVersion->schema, 'problems' => []])),
            Action::make('versionHistory')
                ->label('Version history')
                ->icon('heroicon-o-clock')
                ->color('gray')
                ->modalSubmitAction(false)
                ->modalWidth('3xl')
                ->modalHeading('Version history')
                ->modalContent(fn (Form $record): \Illuminate\Contracts\View\View => view('filament.forms.versions', ['form' => $record->load('versions')])),
            DeleteAction::make()
                ->visible(fn (Form $record): bool => ! $record->isGlobal() && ! $record->isInUse() && ($record->event_id === null || ! in_array($record->id, [$record->event?->enrollment_form_id, $record->event?->info_form_id], true)))
                ->modalDescription('Forms that companies have already answered cannot be deleted, so their answers stay readable.'),
        ];
    }
}
